        //   必须在 exec node 之前打印，此时 bash 尚未被 node 取代，输出能进 dsh-web.log 被扫描。
        // r73（A2 补齐生产者）：原来只有 start_dsh 一个生产者，termux_init / error /
        //   crashed / stopped 全缺，Java 侧解析器虽已就绪却收不到这些态
        //   （见 docs/真机验证清单-DSH_STATE协议.md §10）。此处补齐，且严格用
