        + "  try { require('./dsh-saf-shim.js'); } catch (e) { }\n"
        + "})();\n";

    /**
     * 补齐 koffi 的原生模块。
     *
     * bundle 里只有 @koromix/koffi-android-arm64/android_arm64/koffi.node，
     * 而 koffi 的加载器只在两处找本机二进制：
     *   1) node_modules/@koromix/koffi-<platform>-<arch>（platform 报 android 时命中）
     *   2) node_modules/koffi/build/koffi/<platform>_<abi>/koffi.node（"<abi>" = process.arch）
     * Termux 的 node 可能报告 platform=linux 也可能报 android，两种都覆盖。
     * 缺失时 dsh 整个 cordis profile 加载失败并抛
     * "Cannot find the native Koffi module"，对外表现就是根路径 401 / 无响应。
     */
    private static void ensureKoffiNative(Context ctx) {
        try {
            File nm = new File(home(ctx), "node_modules");
            File srcAndroid = new File(nm, "@koromix/koffi-android-arm64/android_arm64/koffi.node");
            File srcLinux = new File(nm, "@koromix/koffi-linux-arm64/linux_arm64/koffi.node");
            File src = null;
            if (srcAndroid.exists() && srcAndroid.length() > 0) src = srcAndroid;
            else if (srcLinux.exists() && srcLinux.length() > 0) src = srcLinux;
            if (src == null) {
                Log.w(TAG, "找不到 koffi 原生模块来源，跳过补齐（node_modules/@koromix 不存在？）");
                return;
            }
            String[] variants = {"android_arm64", "linux_arm64"};
            for (String variant : variants) {
                File dir = new File(nm, "koffi/build/koffi/" + variant);
                File dst = new File(dir, "koffi.node");
                if (dst.exists() && dst.length() == src.length()) continue;
                dir.mkdirs();
                copyFile(src, dst);
                dst.setReadable(true, false);
                dst.setExecutable(true, false);
            }
            Log.i(TAG, "koffi 原生模块已就位 (" + src.length() + " 字节)");
        } catch (Throwable e) {
            Log.e(TAG, "补齐 koffi 原生模块失败", e);
        }
    }

    private static void copyFile(File src, File dst) throws Exception {
        java.io.InputStream in = new java.io.FileInputStream(src);
        try {
            java.io.OutputStream out = new java.io.FileOutputStream(dst);
            try {
                byte[] buf = new byte[65536];
                int n;
                while ((n = in.read(buf)) > 0) out.write(buf, 0, n);
            } finally { out.close(); }
        } finally { in.close(); }
    }

